# Identify SNPs above a specified empirical FST quantile
fst.alta <- function (snpsfst, percent){ ## snpsfst contains locus-specific FST values; percent = 0.99 selects the upper 1%
  alta <- quantile(snpsfst,probs=percent) ## Calculate the selected empirical FST quantile
  fst.snp <- data.frame (SNPs=c(1:length(snpsfst[snpsfst>=0])), Fst = snpsfst[snpsfst>=0], Dif = snpsfst[snpsfst>=0]>alta) # Store non-negative FST values and flag loci above the threshold
  grafica <- ggplot(fst.snp, aes(x=SNPs, y=Fst, colour=Dif, label=)) + geom_point(shape=19, size= 4, alpha=0.6)+scale_colour_brewer(palette="Set1")+guides(colour="none")+ theme_bw()+ ylab(expression(paste("F"[ST],sep=""))) # Plot locus-specific FST values and candidate status
  snps.alta <- snpsfst[snpsfst>alta] # Retain SNPs above the FST threshold
  return(list(Fst.value=alta, snp.info=snps.alta,fst.snp=fst.snp, grafica=grafica))
}

